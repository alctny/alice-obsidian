import { watch } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const projectDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(projectDir, 'src');
const assetPattern = /url\((["'])(\.\/assets\/[^"'\r\n]+\.svg)\1\)/g;
let buildSequence = 0;

export async function buildTheme({
  mode = 'release',
  themeDir = projectDir,
  resourceBase,
  source = sourceDir,
} = {}) {
  if (!['release', 'dev'].includes(mode)) throw new Error(`Unknown mode: ${mode}`);
  let base;
  if (mode === 'dev') {
    if (!themeDir || !isAbsolute(themeDir)) {
      throw new Error('dev.config.json: themeDir must be an absolute path.');
    }
    const destination = resolve(themeDir);
    const sourcePath = resolve(source);
    if (destination === projectDir || destination === sourcePath || destination.startsWith(`${sourcePath}${sep}`)) {
      throw new Error('Use a separate test theme directory outside the project source.');
    }
    if (!resourceBase) throw new Error('dev.config.json: resourceBase is required.');
    base = new URL(resourceBase);
    base.search = '';
    base.hash = '';
    if (!base.pathname.endsWith('/')) base.pathname += '/';
  }

  const css = await readFile(join(source, 'theme.css'), 'utf8');
  const manifest = await readFile(join(projectDir, 'manifest.json'), 'utf8');
  const assets = new Map();
  for (const match of css.matchAll(assetPattern)) {
    const asset = match[2];
    if (!assets.has(asset)) assets.set(asset, await readFile(resolve(source, asset)));
  }

  const version = `${Date.now()}-${++buildSequence}`;
  const urls = new Map();
  for (const [asset, bytes] of assets) {
    if (mode === 'release') {
      urls.set(asset, `data:image/svg+xml;base64,${bytes.toString('base64')}`);
    } else {
      const filename = asset.slice('./assets/'.length);
      const url = new URL(filename.split('/').map(encodeURIComponent).join('/'), base);
      url.searchParams.set('v', version);
      urls.set(asset, url.href);
    }
  }

  const output = `/* Generated by scripts/build.mjs (${mode}). Edit src/theme.css and src/assets/. */\n` +
    css.replace(assetPattern, (_, quote, asset) => `url("${urls.get(asset)}")`);
  await mkdir(themeDir, { recursive: true });
  if (mode === 'dev') {
    for (const [asset, bytes] of assets) {
      const destination = resolve(themeDir, asset);
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, bytes);
    }
  }
  if (resolve(themeDir) !== projectDir) await writeFile(join(themeDir, 'manifest.json'), manifest);
  // Write CSS last so Obsidian reloads only after its SVG files are ready.
  await writeFile(join(themeDir, 'theme.css'), output);
  return { css: output, assetCount: assets.size };
}

export async function watchTheme(options, report = console.log) {
  const settings = { ...options, mode: 'dev' };
  const initial = await buildTheme(settings);
  report(`Dev: ${initial.assetCount} SVGs → ${settings.themeDir}`);
  let timer;
  let closed = false;
  let activeBuild = Promise.resolve();

  async function rebuild() {
    if (closed) return;
    try {
      const result = await buildTheme(settings);
      report(`Dev updated: ${result.assetCount} SVGs → ${settings.themeDir}`);
    } catch (error) {
      console.error(`Dev build failed: ${error.message}`);
    }
  }

  const watchers = [];
  const folders = [options.source ?? sourceDir, join(options.source ?? sourceDir, 'assets')];
  try {
    for (const folder of folders) {
      watchers.push(watch(folder, () => {
        clearTimeout(timer);
        timer = setTimeout(() => { activeBuild = activeBuild.then(rebuild); }, 80);
      }));
    }
  } catch (error) {
    for (const watcher of watchers) watcher.close();
    throw error;
  }

  return async () => {
    closed = true;
    clearTimeout(timer);
    for (const watcher of watchers) watcher.close();
    await activeBuild;
  };
}

async function main() {
  const [command = 'build', configFile, ...extra] = process.argv.slice(2);
  if (extra.length || !['build', 'dev'].includes(command) || (command === 'build' && configFile)) {
    throw new Error('Usage: node scripts/build.mjs build | dev [config.json]');
  }
  if (command === 'build') {
    const result = await buildTheme();
    console.log(`Release: embedded ${result.assetCount} SVGs → ${join(projectDir, 'theme.css')}`);
    return;
  }
  const configPath = resolve(projectDir, configFile ?? 'dev.config.json');
  const config = JSON.parse(await readFile(configPath, 'utf8'));
  if (!config.themeDir) throw new Error(`${configPath}: themeDir is required.`);
  const close = await watchTheme({ themeDir: config.themeDir, resourceBase: config.resourceBase });
  const stop = async () => {
    await close();
    process.exitCode = 0;
  };
  process.once('SIGINT', stop);
  process.once('SIGTERM', stop);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
