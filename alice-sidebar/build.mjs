import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const source = dirname(fileURLToPath(import.meta.url));
const output = resolve(source, '../dist/alice-sidebar');

export async function buildPlugin(destination = output) {
  // Obsidian loads one entry script; keep local modules inside that script.
  const modules = [];
  for (const filename of (await readdir(join(source, 'src'))).sort()) {
    if (!filename.endsWith('.cjs')) continue;
    const code = await readFile(join(source, 'src', filename), 'utf8');
    modules.push(`${JSON.stringify('./' + filename)}: function(module, exports, require) {\n${code}\n}`);
  }
  const bundle = `// Generated by alice-sidebar/build.mjs. Edit alice-sidebar/src/.\n` +
    `const modules = {\n${modules.join(',\n')}\n};\n` +
    `const cache = Object.create(null);\n` +
    `function load(id) {\n` +
    `  if (id === 'obsidian') return require('obsidian');\n` +
    `  if (!Object.hasOwn(modules, id)) throw new Error('Unknown plugin module: ' + id);\n` +
    `  if (!cache[id]) {\n` +
    `    const local = cache[id] = { exports: {} };\n` +
    `    modules[id](local, local.exports, load);\n` +
    `  }\n` +
    `  return cache[id].exports;\n` +
    `}\nmodule.exports = load('./plugin.cjs');\n`;
  await mkdir(destination, { recursive: true });
  for (const name of ['manifest.json']) {
    await cp(join(source, name), join(destination, name));
  }
  const cheshire = await readFile(join(source, 'assets/cheshire.svg'));
  const hare = await readFile(join(source, 'assets/march-hare.svg'));
  const styles = (await readFile(join(source, 'styles.css'), 'utf8'))
    .replace('./assets/march-hare.svg', `data:image/svg+xml;base64,${hare.toString('base64')}`)
    .replace('./assets/cheshire.svg', `data:image/svg+xml;base64,${cheshire.toString('base64')}`);
  await writeFile(join(destination, 'styles.css'), styles);
  await writeFile(join(destination, 'main.js'), bundle);
  // Remove files emitted by the previous multi-file packaging format.
  await rm(join(destination, 'src'), { recursive: true, force: true });
  await rm(join(destination, 'package.json'), { force: true });
  return destination;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(`Plugin: ${await buildPlugin()}`);
}
